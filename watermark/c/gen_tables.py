"""Write wm_tables.h: the filters and the ID frame's whitening sequence the C port
(watermark/c/wm.c) shares with the Python prototype (harmonic.py, fmchan.py, fec.py).

python watermark/c/gen_tables.py > watermark/c/wm_tables.h
python watermark/c/gen_tables.py --check    # fail if the committed file differs
"""
import os, sys
import numpy as np
from scipy import signal

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import harmonic as hm, fmchan as fc, fec


def arr(name, a, per=4):
    a = np.asarray(a, float).ravel()
    rows = [", ".join(f"{v:.17g}" for v in a[i:i + per]) for i in range(0, len(a), per)]
    return f"static const double {name}[{len(a)}] = {{\n  " + ",\n  ".join(rows) + "\n};\n"


def sos(name, s):
    return f"#define {name.upper()}_N {len(s)}\n" + arr(name, s, 6)


def main():
    p = hm.Params()
    code = fec.Code(nsub=p.nsub)
    max_rate = fc.FS_RF // fc.FS_AUDIO
    fir = signal.firwin(2 * 10 * max_rate + 1, 1.0 / max_rate, window=("kaiser", 5.0))
    pre_b, pre_a = fc._emph(fc.FS_AUDIO, True)
    de_b, de_a = fc._emph(fc.FS_AUDIO, False)
    out = [
        "/* Generated by watermark/c/gen_tables.py from harmonic.py, fmchan.py and fec.py. Do not edit.",
        " * SPDX-License-Identifier: MIT */",
        "#ifndef WM_TABLES_H", "#define WM_TABLES_H", "",
        "/* scipy second-order sections, rows of b0 b1 b2 a0 a1 a2 */",
        sos("sos_lpf", signal.butter(2, p.lpf, "low", fs=hm.FS, output="sos")),
        sos("sos_voice", fc._voice_bp(hm.FS)),
        sos("sos_tx_lp", signal.butter(6, 3000, "low", fs=fc.FS_AUDIO, output="sos")),
        sos("sos_tx_hp", signal.butter(2, 250, "high", fs=fc.FS_AUDIO, output="sos")),
        sos("sos_if", signal.butter(5, 5500, "low", fs=fc.FS_RF, output="sos")),
        "/* 750 us pre-emphasis and de-emphasis (b0 b1 a0 a1), unity gain at 1 kHz */",
        arr("emph_pre", list(pre_b) + list(pre_a)),
        arr("emph_de", list(de_b) + list(de_a)),
        f"/* resample_poly's anti-alias filter for 8 kHz <-> 48 kHz (unscaled firwin, kaiser 5) */",
        f"#define RS_RATE {max_rate}",
        f"#define RS_HALF {10 * max_rate}",
        arr("rs_fir", fir),
        "/* fec.Code: whitening bits (numpy default_rng(0x7E)) and the stride permutation */",
        f"#define WM_NCODED {code.n}",
        "static const unsigned char wm_pn[WM_NCODED] = {\n  "
        + ",\n  ".join(", ".join(str(int(v)) for v in code.pn[i:i + 31]) for i in range(0, code.n, 31))
        + "\n};",
        f"#define WM_STRIDE 37",
        "", "#endif", "",
    ]
    text = "\n".join(out)
    if "--check" in sys.argv:
        with open(os.path.join(HERE, "wm_tables.h")) as f:
            if f.read() != text:
                sys.exit("watermark/c/wm_tables.h differs from gen_tables.py; regenerate it")
        print("wm_tables.h up to date")
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
