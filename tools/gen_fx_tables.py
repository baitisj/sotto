"""Write the constant tables of the fixed-point sotto (c/fixed/) as C source.

Usage: python tools/gen_fx_tables.py [--codebook CB.npz] OUT.c

Every table is an integer array, so the fixed-point code needs no floating point at run
time (the C5517 has no FPU). Formats are given next to each table; see c/fixed/fx.h.
The codebook is rounded to 8-bit integers times one scale per stage, exactly as
vocoder_lab.round_codebook does for v3.6.
"""
import argparse
import numpy as np

FS, K, NSAMP = 8000, 20, 80
WO_MIN, WO_HI = 2 * np.pi / 160, 2 * np.pi / 16


def mel(f):
    return np.floor(2595 * np.log10(1 + f / 700) + 0.5)


def arr(f, ctype, name, vals, per_line=12, comment=""):
    vals = [int(v) for v in np.asarray(vals).ravel()]
    if comment:
        f.write("/* %s */\n" % comment)
    f.write("const %s %s[%d] = {\n" % (ctype, name, len(vals)))
    for i in range(0, len(vals), per_line):
        f.write("  " + ", ".join(str(v) for v in vals[i:i + per_line]) + ",\n")
    f.write("};\n\n")


def rnd(x):
    return np.floor(np.asarray(x, float) + 0.5).astype(np.int64)


def main(cb_path, out):
    a, b = mel(200.0), mel(3700.0)
    m = np.array([b if k == K - 1 else a + k * (b - a) / (K - 1) for k in range(K)])
    kfreq = 700 * (10 ** (m / 2595) - 1)
    pre = 20 * np.log10(kfreq / 300.0)
    dct = np.array([[np.sqrt(2.0 / K) * np.cos(np.pi * (n + 0.5) * k / K) / (np.sqrt(2.0) if k == 0 else 1.0)
                     for n in range(K)] for k in range(K)])
    wo = np.exp(np.log(WO_MIN) + np.arange(128) * (np.log(WO_HI) - np.log(WO_MIN)) / 127)
    kf16 = rnd(kfreq * 16)
    d = np.load(cb_path)
    bits = [int(x) for x in d["bits"]]
    assert sum(bits) == 34 and len(bits) <= 5

    with open(out, "w") as f:
        f.write("/* Generated by tools/gen_fx_tables.py (codebook %s). Do not edit.\n"
                " * SPDX-License-Identifier: MIT */\n#include \"fx.h\"\n#include \"fx_tables.h\"\n\n"
                % cb_path.split("/")[-1])
        arr(f, "int16_t", "fx_cos512", rnd(np.minimum(np.cos(2 * np.pi * np.arange(512) / 512) * 32768, 32767)),
            comment="cos(2 pi i / 512), Q15 (1.0 saturates to 32767)")
        arr(f, "uint32_t", "fx_wo_tab", rnd(wo / (2 * np.pi) * 2 ** 32), per_line=8,
            comment="Wo of each 7-bit pitch index, in turns per sample x 2^32 (Q32)")
        arr(f, "int32_t", "fx_kfreq", kf16, comment="rate-K sample frequencies, Hz Q4")
        arr(f, "int32_t", "fx_kinvw", rnd(65536.0 * 65536 / np.diff(kf16)), per_line=8,
            comment="2^32 / (kfreq[k+1] - kfreq[k]) in Q4 Hz, for linear interpolation (Q16 fraction)")
        arr(f, "int32_t", "fx_pre", rnd(pre * 256), comment="postfilter pre-emphasis, dB Q8")
        arr(f, "int16_t", "fx_dct", rnd(dct * 32768), per_line=10,
            comment="orthonormal DCT-II [k][n], Q15")
        pn = [i / 80 for i in range(80)] + [1 - (i - 80) / 80 for i in range(80, 160)]
        arr(f, "int16_t", "fx_pn", rnd(np.array(pn) * 16384), per_line=16,
            comment="triangular overlap-add window (Codec 2's synthesis window for 10 ms frames), Q14")
        x = np.arange(257) / 256
        arr(f, "int32_t", "fx_log2_tab", rnd(np.log2(1 + x) * 2 ** 30), per_line=8,
            comment="log2(1 + i/256), Q30")
        arr(f, "uint32_t", "fx_exp2_tab", rnd(2 ** x * 2 ** 30), per_line=8,
            comment="2^(i/256), Q30")
        # ---- encoder
        nw, mp = 279, 320
        j = np.arange(2 * (nw // 2))
        hann = (0.5 - 0.5 * np.cos(2 * np.pi * j / (nw - 1))).astype(np.float32).astype(float)
        arr(f, "int16_t", "fx_hann", rnd(np.minimum(hann * 32768, 32767)), per_line=12,
            comment="Codec 2's 279-point analysis window (samples 21..298 of 320, Hann), Q15")
        wn = 1 / np.sqrt(np.sum(hann ** 2) * 512)          # Codec 2's normalisation
        f.write("/* log2(512 wn / 32768), Q16, wn being Codec 2's window normalisation: the float\n"
                "   spectrum is the fixed one x 2^(frame exponent) x 2^(this) (sotto_fx_enc.c, analyse) */\n")
        f.write("const int32_t fx_sw_l2 = %d;\n\n" % int(rnd(np.log2(wn * 512 / 32768) * 65536)))
        ws = np.zeros(512)
        w = np.zeros(mp)
        w[mp // 2 - nw // 2:mp // 2 - nw // 2 + len(hann)] = hann * wn
        ws[:nw // 2] = w[mp // 2:mp // 2 + nw // 2]
        ws[512 - nw // 2:] = w[mp // 2 - nw // 2:mp // 2]
        W = np.fft.fft(ws).real
        W = np.concatenate([W[256:], W[:256]])
        arr(f, "int16_t", "fx_W", rnd(W / W[256] * 32767), per_line=12,
            comment="frequency response of the analysis window, centred on 256, peak 32767")
        n = np.arange(48) - 23.5
        h = np.sinc(2 * 600 / 8000 * n) * np.hamming(48)
        h /= h.sum()
        arr(f, "int16_t", "fx_nlp_fir", rnd(h * 32768), per_line=12,
            comment="NLP decimation filter: 48-tap 600 Hz low-pass, Hamming window, Q15")
        arr(f, "int16_t", "fx_nlp_win", rnd(np.minimum((0.5 - 0.5 * np.cos(2 * np.pi * np.arange(64) / 63)) * 32768, 32767)),
            per_line=16, comment="NLP DFT window, 64-point Hann, Q15")
        bb = np.arange(65)
        arr(f, "int16_t", "fx_nlp_bmin", [int(0.8 * b) for b in bb], per_line=16,
            comment="(int)(0.8 b) and (int)(1.2 b) in double precision, for the NLP's sub-multiple search")
        arr(f, "int16_t", "fx_nlp_bmax", [int(1.2 * b) for b in bb], per_line=16)
        lo, hi = np.log(WO_MIN), np.log(WO_HI)
        thr = np.exp(lo + (np.arange(127) + 0.5) * (hi - lo) / 127)
        arr(f, "uint32_t", "fx_wo_thr", np.ceil(thr / (2 * np.pi) * 2 ** 32), per_line=8,
            comment="pitch index decision levels: index = number of levels <= Wo (Q32 turns)")
        f.write("const int16_t fx_cb_stages = %d;\n" % len(bits))
        f.write("const int16_t fx_cb_bits[] = {%s};\n" % ", ".join(map(str, bits)))
        scales = []
        for s, nb in enumerate(bits):
            c = d[f"stage{s}"].astype(np.float32).astype(float)
            assert c.shape == (2 ** nb, K - 1)
            step = np.abs(c).max() / 127
            q = np.round(c / step)
            assert np.abs(q).max() <= 127
            scales.append(step)
            # two 8-bit values per 16-bit word (the C55x has no 8-bit type), high byte
            # first, each vector padded with a zero to 20 values = FX_CBW words
            # (FX_CB_UNPACKED: one value per word, twice the memory, a faster search)
            qp = np.concatenate([q, np.zeros((len(q), 1))], 1).astype(np.int64)
            words = (qp[:, 0::2] << 8) | (qp[:, 1::2] & 0xFF)
            words = np.where(words >= 32768, words - 65536, words)
            f.write("#ifdef FX_CB_UNPACKED\n")
            arr(f, "int16_t", "fx_cb%d" % s, qp, per_line=20,
                comment="stage %d: 2^%d vectors of %d values" % (s, nb, K))
            f.write("#else\n")
            arr(f, "int16_t", "fx_cb%d" % s, words, per_line=10,
                comment="stage %d: 2^%d vectors of %d words, two 8-bit values each" % (s, nb, K // 2))
            f.write("#endif\n")
            arr(f, "int32_t", "fx_cb%d_e2" % s, (q ** 2).sum(1), per_line=12,
                comment="squared length of each vector of stage %d, in steps^2" % s)
        f.write("const int16_t *const fx_cb[] = {%s};\n" % ", ".join("fx_cb%d" % s for s in range(len(bits))))
        f.write("const int32_t *const fx_cb_e2[] = {%s};\n" % ", ".join("fx_cb%d_e2" % s for s in range(len(bits))))
        f.write("/* value of one codebook step, dB x 2^16, and its inverse, x 2^22 / dB Q8 */\n")
        f.write("const int32_t fx_cb_step[] = {%s};\n" % ", ".join(str(int(rnd(s * 65536))) for s in scales))
        f.write("const int32_t fx_cb_istep[] = {%s};\n" % ", ".join(str(int(rnd(2 ** 22 / (s * 256)))) for s in scales))


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--codebook", default="sim/data/shape_msvq_9988.npz")
    p.add_argument("out")
    a = p.parse_args()
    main(a.codebook, a.out)
