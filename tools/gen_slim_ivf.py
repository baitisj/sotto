"""Cell index for the slim sotto 1200 encoder's codebook search (c/fixed/sotto_fx_slim.c,
docs/sotto-slim.md): c/fixed/slim_cells.h.

For stages 1-3 of the 9+9+8+8 shape codebook: C centroids (k-means over the first CD values of
the stage's own vectors, 8-bit values in the stage's steps) and, per centroid, the list of the
vectors nearest it. The encoder compares its target with the centroids, then only with the
vectors of the PROBE nearest cells, so it reads tens of vectors a stage instead of 256 or 512:
on the K6 the codebook is in SPI flash, and a read costs more than a comparison.

  python3 tools/gen_slim_ivf.py [--codebook CB.npz] [--c 64,64,32] [--cd 8] [-v] OUT.h

The codebook's 8-bit values are tools/gen_fx_tables.py's. No random numbers: the k-means
starts from the vectors farthest apart, so the table is the same on every machine.
SPDX-License-Identifier: MIT"""
import os
import sys

import numpy as np


def stage_values(cb_path, s):
    """stage s as tools/gen_fx_tables.py rounds it: integers in the stage's own steps"""
    c = np.load(cb_path)[f"stage{s}"].astype(np.float32).astype(float)
    return np.round(c / (np.abs(c).max() / 127)).astype(int)


def kmeans(x, c, it=100):
    cen = [x[0].astype(float)]                      # farthest-point start
    d = ((x - cen[0]) ** 2).sum(1)
    while len(cen) < c:
        cen.append(x[int(d.argmax())].astype(float))
        d = np.minimum(d, ((x - cen[-1]) ** 2).sum(1))
    cen = np.array(cen)
    for _ in range(it):
        d = ((x[:, None, :] - cen[None]) ** 2).sum(2)
        a = d.argmin(1)
        new = cen.copy()
        for j in range(c):
            if np.any(a == j):
                new[j] = np.rint(x[a == j].mean(0))   # whole numbers: no drift between machines
        if np.array_equal(new, cen):
            break
        cen = new
    return np.clip(cen, -127, 127).astype(int)


def main():
    a = sys.argv[1:]
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    cs, cd, cb = [64, 64, 32], 8, os.path.join(root, "sim", "data", "shape_msvq_9988.npz")
    if "--c" in a:
        i = a.index("--c"); cs = [int(v) for v in a[i + 1].split(",")]; del a[i:i + 2]
    if "--cd" in a:
        i = a.index("--cd"); cd = int(a[i + 1]); del a[i:i + 2]
    verbose = "-v" in a
    if verbose:
        a.remove("-v")
    if "--codebook" in a:
        i = a.index("--codebook"); cb = a[i + 1]; del a[i:i + 2]
    sizes, out, maxn = [512, 512, 256], [], 0
    out.append("/* Generated by tools/gen_slim_ivf.py --c %s --cd %d: the slim encoder's codebook cells"
               % (",".join(map(str, cs)), cd))
    out.append(" * (c/fixed/sotto_fx_slim.c, docs/sotto-slim.md).")
    out.append(" * SPDX-License-Identifier: MIT */")
    out.append("#define IVF_CD %d                 /* bytes of a centroid: the vectors' first IVF_CD values */" % cd)
    for s, n in enumerate(sizes):
        x = stage_values(cb, s)
        assert x.shape == (n, 19)
        nv = min(cd, 19)
        cen = kmeans(x[:, :nv], cs[s])
        d = ((x[:, None, :nv] - cen[None]) ** 2).sum(2)
        cell = d.argmin(1)
        lists = [[v for v in range(n) if cell[v] == j] for j in range(cs[s])]
        off = np.cumsum([0] + [len(l) for l in lists])
        maxn = max(maxn, max(map(len, lists)))
        out.append("#define IVF_C%d %d" % (s, cs[s]))
        out.append("static const signed char ivf_cen%d[%d * IVF_CD] = {   /* value k at byte k ^ 1, as the codebook's packed words */" % (s, cs[s]))
        for row in cen:
            b = [0] * 20
            for k in range(nv):
                b[k ^ 1] = row[k]
            out.append("  " + ", ".join(str(v) for v in b[:cd]) + ",")
        out.append("};")
        out.append("static const uint16_t ivf_off%d[%d] = {%s};" % (s, cs[s] + 1, ", ".join(map(str, off))))
        if n > 256:                                 # a list is in rising order: this many of its vectors are below 256
            out.append("static const unsigned char ivf_lo%d[%d] = {%s};"
                       % (s, cs[s], ", ".join(str(sum(v < 256 for v in l)) for l in lists)))
        flat = [v & 255 for l in lists for v in l]
        out.append("static const unsigned char ivf_idx%d[%d] = {   /* the vectors' numbers, mod 256 */" % (s, len(flat)))
        for i in range(0, len(flat), 20):
            out.append("  " + ", ".join(map(str, flat[i:i + 20])) + ",")
        out.append("};")
        if verbose:
            sys.stderr.write("stage %d: %d cells of %d..%d vectors\n"
                             % (s, cs[s], min(map(len, lists)), max(map(len, lists))))
    out.append("#define IVF_MAXN %d              /* vectors in the largest cell */" % maxn)
    with open(a[0], "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
